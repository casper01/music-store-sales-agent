"""Markdown rendering of evaluation reports and recorded sessions."""

from __future__ import annotations

import json
from collections.abc import Sequence
from datetime import UTC, datetime

from sales_agent.agent.contracts import AgentResult, ToolCallRecord
from sales_agent.evaluation.evaluator import EvalReport


def _timestamp() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")


def format_tool_call(call: ToolCallRecord) -> str:
    status = "ok" if call.ok else f"error: {call.error}"
    if call.name == "run_sql":
        detail = f"\n\n```sql\n{call.arguments.get('query', '').strip()}\n```"
    elif call.arguments:
        detail = f" `{json.dumps(call.arguments, ensure_ascii=False)}`"
    else:
        detail = ""
    return f"- **{call.name}** ({status}){detail}"


def _quote(text: str) -> str:
    return "\n".join(f"> {line}" if line else ">" for line in text.splitlines())


def render_session(model: str, transcript: Sequence[tuple[str, AgentResult]]) -> str:
    lines = [
        "# Example session",
        "",
        f"Generated by `sales-agent session` on {_timestamp()} with model `{model}`.",
        "Answers and tool calls below are the live, unedited output of that run.",
        "",
    ]
    for number, (question, result) in enumerate(transcript, start=1):
        lines += [f"## {number}. {question}", "", "**Tool calls**", ""]
        lines += [format_tool_call(call) for call in result.tool_calls] or ["- (none)"]
        lines += [
            "",
            f"**Answer** (stop reason: `{result.stop_reason}`, iterations: {result.iterations})",
            "",
            _quote(result.answer),
            "",
        ]
    return "\n".join(lines)


def render_eval_report(model: str, report: EvalReport) -> str:
    total = len(report.results)
    lines = [
        "# Evaluation report",
        "",
        f"Generated on {_timestamp()} with model `{model}`.",
        "",
        f"- Passed cases: **{report.passed_count}/{total}**",
        f"- Database unchanged (SHA-256 before == after): **{report.database_unchanged}**",
        "",
        "| # | Result | Tools used | Failures |",
        "|---|--------|------------|----------|",
    ]
    for result in report.results:
        tools = ", ".join(result.tool_names) or "-"
        failures = "<br>".join(result.failures).replace("|", "\\|") or "-"
        status = "PASS" if result.passed else "FAIL"
        lines.append(f"| {result.case.id} | {status} | {tools} | {failures} |")

    lines += ["", "## Answers", ""]
    for result in report.results:
        lines += [
            f"### {result.case.id}. {result.case.question}",
            "",
            f"*Criteria:* {result.case.criteria}",
            "",
            *[format_tool_call(call) for call in result.tool_calls],
            "",
            _quote(result.answer or "(no answer)"),
            "",
        ]
    return "\n".join(lines)
